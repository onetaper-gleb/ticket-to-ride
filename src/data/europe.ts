const pairKey = (a: string, b: string) => [a, b].sort().join('--');
const pairCounts = new Map<string, number>();
for (const [a, b] of routeDefinitions) {
  const pair = pairKey(a, b);
  pairCounts.set(pair, (pairCounts.get(pair) ?? 0) + 1);
}
const pairIndexes = new Map<string, number>();
export const EDGES: Edge[] = routeDefinitions.map(
  ([a, b, color, length, tunnel = false, ferries = 0]) => {
    const pair = pairKey(a, b);
    const index = (pairIndexes.get(pair) ?? 0) + 1;
    pairIndexes.set(pair, index);
    return {
      id: `${pair}-${index}`,
      a,
      b,
      color,
      length,
      tunnel,
      ferries,
      parallel: pairCounts.get(pair) === 2 ? pair : null,
      owner: null,
    };
  },
);

